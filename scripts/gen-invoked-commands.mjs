// 构建期资产生成器：grep src/ 所有 invoke('xxx') 调用，提取 command 名集合，
// 写入 src/generated/invoked-commands.ts。供 P4「IPC 接线自审」作前端 F 集合真相源
// （后端 B 集合来自 include_str! lib.rs 的 generate_handler!）。双集合独立 grep 后
// 比对：F\B = 死按钮（前端调了后端没注册）→ FAIL；B\F = 死代码 → WARN。
//
// 触发点：vite plugin（dev server 启动 + build 开始）+ 可直接 `node` 运行。
// manifest 入库（首次生成后 git add），CI 单测验证它与源码同步。
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const SRC_ROOT = join(here, '..', 'src');
const OUT_FILE = join(SRC_ROOT, 'generated', 'invoked-commands.ts');

// 跳过测试夹具、生成物、第三方——它们不是产品代码的真实 IPC 调用点。
const SKIP_DIRS = new Set(['__tests__', 'generated', 'node_modules']);
// 匹配 invoke('xxx') 和泛型 invoke<T>('xxx') 两种形态（dev workbench 大量用泛型 invoke
// 传返回类型，如 invoke<CostSummary>('get_cost_summary')）。<[^>]*> 单层泛型够用。
const RE = /invoke(?:<[^>]*>)?\(\s*['"]([^'"]+)['"]/g;

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) {
      if (SKIP_DIRS.has(name)) continue;
      out.push(...walk(p));
    } else if (/\.(ts|tsx)$/.test(name)) {
      out.push(p);
    }
  }
  return out;
}

/** 提取 src/ 所有真实 invoke('xxx') 的 command 名（去重 + 排序）。 */
export function collectInvokedCommands() {
  const cmds = new Set();
  for (const file of walk(SRC_ROOT)) {
    let src = readFileSync(file, 'utf8');
    // 1) 剥离块注释（含跨行 JSDoc /** ... */）——注释里举例的 invoke('xxx') 不是
    //    真实调用点，不能进 F 集合污染比对。
    src = src.replace(/\/\*[\s\S]*?\*\//g, '');
    // 2) 丢掉整行注释（//、*、/* 开头）。注意：只丢【整行】注释，保留行内 // ——
    //    因为 invoke 的 command 名是 snake_case 标识符，永不含 //；而 `'http://…'`
    //    这类含 // 的字符串字面量若被 //.*$ 截断会把同行的真 invoke 一起吞掉（回归）。
    //    整行注释开头判断与原逐行逻辑等价，不回归行内场景。
    const kept = src
      .split('\n')
      .filter((line) => {
        const t = line.trim();
        return !(t.startsWith('//') || t.startsWith('*') || t.startsWith('/*'));
      })
      .join('\n');
    // 3) 整体匹配（不逐行）：RE 里 \s* 跨行，能捕获 invoke( 与字符串字面量分布在不同
    //    行的多行调用（如 skillsStore.ts 的 invoke<T>(\n  'skill_catalog',\n)）。
    //    逐行扫描正是反刷分自审的破洞：多行 invoke 被静默漏采 → F 缺该命令 → 即便
    //    后端从 generate_handler! 删了它，F\B 也为空，审计假性 PASS。整体匹配闭合该缺口。
    RE.lastIndex = 0;
    let m;
    while ((m = RE.exec(kept))) cmds.add(m[1]);
  }
  return [...cmds].sort();
}

/** 重新生成 manifest 文件，返回写入的 command 数。 */
export function generateInvokedCommandsFile() {
  const cmds = collectInvokedCommands();
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  const body =
    '// AUTO-GENERATED by scripts/gen-invoked-commands.mjs — do not edit by hand.\n' +
    '// 所有前端 invoke("xxx") 的 IPC command 名（grep 自 src/，去注释/测试/生成物）。\n' +
    '// 用途：P4「IPC 接线自审」的前端 F 集合真相源，与后端 generate_handler! 注册集\n' +
    '// 合比对，抓死按钮（前端调了后端没注册）与死代码（后端注册了前端没调）。\n' +
    `export const INVOKED_COMMANDS: readonly string[] = ${JSON.stringify(cmds)};\n`;
  writeFileSync(OUT_FILE, body);
  return cmds.length;
}

// 直接 `node scripts/gen-invoked-commands.mjs` 运行时生成文件。
const invokedDirectly =
  process.argv[1] && fileURLToPath(`file://${process.argv[1].replace(/\\/g, '/')}`) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const n = generateInvokedCommandsFile();
  console.log(`[gen-invoked-commands] wrote ${n} commands → ${OUT_FILE}`);
}
